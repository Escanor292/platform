// Function to apply Vietnamese labels to tags
export function applyVietnameseLabels<T extends { id: string; label: string }>(tags: T[]): T[] {
  return tags.map(tag => ({
    ...tag,
    label: VIETNAMESE_LABELS[tag.id] || tag.label
  }));
}
